# Fabric Notebook: 05_obras_report
# Builds a PDF of "Obras" expenses, saves it to the Lakehouse, and emails it only when
# there are rows with Notificado_Email = 0 (email outbox; closed out in Cell 9).
# Requires DespesasDEV_Landing as default Lakehouse and GestaoDespesasDW as Warehouse data item.
# Paste each "# CELL n" block into its own notebook cell.
 
# CELL 1 — dependencies
# Pin exact versions: an unpinned xhtml2pdf pulls a newer cryptography that conflicts with
# Fabric's own msal/pyopenssl. RESTART THE SESSION after this cell, before running the next ones.
# %pip install xhtml2pdf==0.2.17 cryptography==46.0.7 reportlab==4.4.10 --quiet
 
import pandas as pd
import smtplib
from email.message import EmailMessage
from xhtml2pdf import pisa
from io import BytesIO
import os
import notebookutils
 
WAREHOUSE_NAME = "GestaoDespesasDW"
OUTPUT_FOLDER = "/lakehouse/default/Files/Output_Obras"
 
# CELL 2 — parameters cell (toggle "parameter cell" in the Fabric UI)
EMAIL_REMETENTE = "<PASTE_SENDER_EMAIL_HERE>"
EMAIL_PASSWORD = "<PASTE_SENDER_APP_PASSWORD_HERE>"
EMAIL_DESTINO = "<PASTE_DESTINATION_EMAIL_HERE>"
 
SMTP_SERVER = "smtp.office365.com"
SMTP_PORT = 587
 
# CELL 3 — connection helper
def get_warehouse_connection():
    return notebookutils.data.connect_to_artifact(WAREHOUSE_NAME)
 
# CELL 4 — connectivity test
conn = get_warehouse_connection()
result = conn.query("SELECT ISNULL(SUM([Valor Gasto (€)]), 0) AS TotalAcumulado FROM dbo.vw_Fact_Obras")
print("Total accumulated in Obras:", result["TotalAcumulado"][0])
 
# CELL 5 — fetch data, only if there are rows pending notification
conn = get_warehouse_connection()
 
pendentes_result = conn.query("SELECT COUNT(*) AS cnt FROM dw.Fact_Obras WHERE Notificado_Email = 0")
pendentes_count = pendentes_result["cnt"][0]
print(f"Obras rows pending email notification: {pendentes_count}")
 
if pendentes_count == 0:
    print("Nothing new since the last send — skipping report generation/sending.")
else:
    total_result = conn.query("SELECT ISNULL(SUM([Valor Gasto (€)]), 0) AS TotalAcumulado FROM dbo.vw_Fact_Obras")
    total_obras = float(total_result["TotalAcumulado"][0])
 
    detalhe_query = """
        SELECT CAST(Data AS DATE) as Data, [Descrição] as Descricao, [Valor Gasto (€)] as Valor
        FROM dbo.vw_Fact_Obras ORDER BY Data DESC
    """
    df_obras = conn.query(detalhe_query)
    if df_obras is None:
        df_obras = pd.DataFrame(columns=["Data", "Descricao", "Valor"])
 
    print(f"Total accumulated: {total_obras:,.2f} €")
    print(f"Detail rows (complete history): {len(df_obras)}")
 
# CELL 6 — generate the PDF
def gerar_pdf(df_obras, total_acumulado):
    df_pdf = df_obras.copy()
    if not df_pdf.empty:
        df_pdf["Data"] = pd.to_datetime(df_pdf["Data"]).dt.strftime("%d/%m/%Y")
        df_pdf["Valor"] = df_pdf["Valor"].apply(lambda x: f"{x:,.2f} €")
 
    html = f"""
    <html><head><style>
        @page {{ size: A4; margin: 1cm; }}
        body {{ font-family: Helvetica, sans-serif; font-size: 10pt; }}
        h2 {{ color: #0078D4; border-bottom: 2px solid #0078D4; padding-bottom: 5px; }}
        table {{ width: 100%; border-collapse: collapse; }}
        th {{ background-color: #f2f2f2; padding: 8px; border: 1px solid #ddd; text-align: left; }}
        td {{ padding: 8px; border: 1px solid #ddd; }}
    </style></head>
    <body>
        <h2>Obras Expense History - {pd.Timestamp.now().strftime("%d/%m/%Y")}</h2>
        <p style="font-size: 1.2em;">Total accumulated: <b>{total_acumulado:,.2f} €</b></p>
        {df_pdf.to_html(index=False, border=0, justify="left") if not df_pdf.empty else "<p>No Obras records.</p>"}
    </body></html>
    """
    buffer = BytesIO()
    pisa.CreatePDF(html, dest=buffer)
    buffer.seek(0)
    return buffer.read()
 
if pendentes_count > 0:
    pdf_bytes = gerar_pdf(df_obras, total_obras)
    print(f"PDF generated: {len(pdf_bytes)} bytes")
 
# CELL 7 — save the PDF to the Lakehouse
if pendentes_count > 0:
    os.makedirs(OUTPUT_FOLDER, exist_ok=True)
    hoje_fmt = pd.Timestamp.now().strftime("%Y%m%d")
    nome_pdf = f"Relatorio_Obras_{hoje_fmt}.pdf"
    caminho_pdf = os.path.join(OUTPUT_FOLDER, nome_pdf)
 
    with open(caminho_pdf, "wb") as f:
        f.write(pdf_bytes)
 
    print(f"PDF saved to: {caminho_pdf}")
 
# CELL 8 — send the email (local_hostname set explicitly: see docs/email-delivery-notes.md)
def enviar_email(total_acumulado, pdf_bytes, nome_pdf):
    html = f"""
    <html><body style="font-family: Segoe UI, Arial, sans-serif; color: #333;">
        <h2 style="color: #0078D4;">🏗️ Obras Update</h2>
        <p style="font-size: 1.2em;">Total spent on Obras so far: <b>{total_acumulado:,.2f} €</b></p>
        <p>The detailed PDF report is attached.</p>
        <hr style="border: 0; border-top: 1px solid #eee;">
        <p style="font-size: 0.8em; color: #888;">Automatically generated by the Financial Management System (Fabric).</p>
    </body></html>
    """
    msg = EmailMessage()
    msg["Subject"] = f"Obras Report - Accumulated: {total_acumulado:,.2f} €"
    msg["From"], msg["To"] = EMAIL_REMETENTE, EMAIL_DESTINO
    msg.add_alternative(html, subtype="html")
    msg.add_attachment(pdf_bytes, maintype="application", subtype="pdf", filename=nome_pdf)
 
    with smtplib.SMTP(SMTP_SERVER, SMTP_PORT, local_hostname=EMAIL_REMETENTE.split("@")[-1]) as server:
        server.starttls()
        server.login(EMAIL_REMETENTE, EMAIL_PASSWORD)
        server.send_message(msg)
 
if pendentes_count > 0:
    enviar_email(total_obras, pdf_bytes, nome_pdf)
    print("Email sent successfully.")
 
# CELL 9 — mark pending rows as notified
if pendentes_count > 0:
    conn = get_warehouse_connection()
    conn.query("UPDATE dw.Fact_Obras SET Notificado_Email = 1 WHERE Notificado_Email = 0")
    print(f"{pendentes_count} Obras row(s) marked as notified by email.")
 